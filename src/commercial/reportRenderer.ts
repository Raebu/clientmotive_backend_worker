import { PDFDocument, StandardFonts, rgb } from "pdf-lib";
import { Document, Packer, Paragraph, HeadingLevel, TextRun } from "docx";
import PptxGenJS from "pptxgenjs";
import type { Env } from "../types";

type ExportFormat="pdf"|"pptx"|"docx"|"csv"|"html";

function safe(value:unknown):string{
  if(value===null||value===undefined) return "";
  if(typeof value==="string") return value;
  if(typeof value==="number"||typeof value==="boolean") return String(value);
  if(Array.isArray(value)) return value.map(safe).filter(Boolean).join("\n");
  return Object.entries(value as Record<string,unknown>).map(([k,v])=>k+": "+safe(v)).join("\n");
}
function esc(value:string){return value.replace(/[&<>"']/g,(m)=>({"&":"&amp;","<":"&lt;",">":"&gt;","\"":"&quot;","'":"&#039;"}[m]!));}
function contentSections(content:any){
  const pages=Array.isArray(content?.decisionPages)?content.decisionPages:[];
  return [{title:content?.title||"ClientMotive Growth Snapshot",body:content?.executiveSummary||""},
    ...pages.map((p:any)=>({title:String(p.title||"Section"),body:safe(p.content)}))];
}

async function loadExport(env:Env,exportId:string){
  const row=await env.DB.prepare("SELECT * FROM data_exports WHERE export_id=? AND status='complete'").bind(exportId).first<any>();
  if(!row) throw new Error("export_not_found");
  return {row,content:JSON.parse(row.content_json||"{}")};
}

function wrap(text:string,max=86){
  const words=text.replace(/\s+/g," ").trim().split(" "); const lines:string[]=[]; let line="";
  for(const word of words){const next=(line+" "+word).trim();if(next.length>max&&line){lines.push(line);line=word;}else line=next;}
  if(line) lines.push(line);return lines;
}

async function pdf(content:any){
  const doc=await PDFDocument.create();
  const regular=await doc.embedFont(StandardFonts.Helvetica);
  const bold=await doc.embedFont(StandardFonts.HelveticaBold);
  const sections=contentSections(content);
  for(const section of sections){
    let page=doc.addPage([842,595]); let y=535;
    page.drawText(section.title.slice(0,95),{x:52,y,size:22,font:bold,color:rgb(0.04,0.09,0.21)});
    y-=38;
    for(const paragraph of safe(section.body).split("\n").filter(Boolean)){
      for(const line of wrap(paragraph,105)){
        if(y<55){page=doc.addPage([842,595]);y=535;}
        page.drawText(line.slice(0,145),{x:52,y,size:10.5,font:regular,color:rgb(0.16,0.23,0.34)});y-=15;
      }
      y-=7;
    }
    page.drawText("ClientMotive · Evidence-led commercial intelligence",{x:52,y:28,size:8,font:regular,color:rgb(0.4,0.47,0.58)});
  }
  return new Uint8Array(await doc.save());
}

async function docx(content:any){
  const children:any[]=[];
  for(const [i,section] of contentSections(content).entries()){
    children.push(new Paragraph({text:section.title,heading:i===0?HeadingLevel.TITLE:HeadingLevel.HEADING_1}));
    for(const line of safe(section.body).split("\n").filter(Boolean)){
      children.push(new Paragraph({children:[new TextRun({text:line,size:22})],spacing:{after:120}}));
    }
  }
  children.push(new Paragraph({children:[new TextRun({text:"Generated by ClientMotive. Evidence, hypotheses and recommendations should be reviewed before external action.",italics:true,size:18})]}));
  const document=new Document({sections:[{children}]});
  const blob=await Packer.toBlob(document);
  return new Uint8Array(await blob.arrayBuffer());
}

async function pptx(content:any){
  const presentation=new PptxGenJS();
  presentation.layout="LAYOUT_WIDE";
  presentation.author="ClientMotive";
  presentation.subject="Growth Snapshot";
  presentation.title=String(content?.title||"ClientMotive Growth Snapshot");
  for(const [i,section] of contentSections(content).entries()){
    const slide=presentation.addSlide();
    slide.background={color:i===0?"0B1736":"FFFFFF"};
    slide.addText(section.title,{x:0.6,y:0.55,w:12.1,h:0.65,fontFace:"Aptos",fontSize:i===0?28:24,bold:true,color:i===0?"FFFFFF":"0B1736",margin:0});
    const lines=safe(section.body).split("\n").filter(Boolean).slice(0,18).map(t=>({text:t,options:{bullet:{indent:14},hanging:3,breakLine:true}}));
    if(lines.length) slide.addText(lines as any,{x:0.75,y:1.5,w:11.8,h:5.3,fontFace:"Aptos",fontSize:14,color:i===0?"DDE7F5":"33445C",breakLine:false,margin:0.05,valign:"top"});
    slide.addText("ClientMotive · Evidence-led commercial intelligence",{x:0.75,y:7.05,w:5,h:0.2,fontFace:"Aptos",fontSize:7,color:i===0?"9FB4D1":"71839A",margin:0});
  }
  const out=await (presentation as any).write({outputType:"arraybuffer"});
  return new Uint8Array(out as ArrayBuffer);
}

function csv(content:any){
  const rows=[["section","content"]];
  for(const section of contentSections(content)) rows.push([section.title,safe(section.body)]);
  return new TextEncoder().encode(rows.map(row=>row.map(v=>'"'+String(v).replaceAll('"','""')+'"').join(",")).join("\r\n"));
}
function html(content:any){
  const sections=contentSections(content).map((s,i)=>`<section class="${i===0?"cover":""}"><h${i===0?1:2}>${esc(s.title)}</h${i===0?1:2}><pre>${esc(s.body)}</pre></section>`).join("");
  return new TextEncoder().encode(`<!doctype html><html><head><meta charset="utf-8"><title>${esc(content?.title||"ClientMotive Growth Snapshot")}</title><style>body{font:15px/1.55 Arial,sans-serif;color:#263d59;margin:0}section{page-break-after:always;padding:48px;max-width:960px;margin:auto}.cover{background:#0b1736;color:#fff;min-height:620px}h1{font-size:42px;margin-top:120px}h2{font-size:28px;color:#0b1736}pre{white-space:pre-wrap;font:inherit}@media print{section{min-height:650px}}</style></head><body>${sections}</body></html>`);
}

export async function renderDataExport(env:Env,exportId:string,format:ExportFormat){
  const {content}=await loadExport(env,exportId);
  if(format==="pdf") return {bytes:await pdf(content),contentType:"application/pdf",extension:"pdf"};
  if(format==="pptx") return {bytes:await pptx(content),contentType:"application/vnd.openxmlformats-officedocument.presentationml.presentation",extension:"pptx"};
  if(format==="docx") return {bytes:await docx(content),contentType:"application/vnd.openxmlformats-officedocument.wordprocessingml.document",extension:"docx"};
  if(format==="csv") return {bytes:csv(content),contentType:"text/csv; charset=utf-8",extension:"csv"};
  if(format==="html") return {bytes:html(content),contentType:"text/html; charset=utf-8",extension:"html"};
  throw new Error("unsupported_export_format");
}
